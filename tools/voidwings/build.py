"""Writes the generated Luau data module from layout.py and rebuilds the
command-bar installer.

    python3 tools/voidwings/build.py

  src/ReplicatedStorage/Cosmetics/VoidWings/VoidWingsData.luau  (geometry + motion)
  install/InstallVoidWings.lua                                  (one paste in Studio)
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import layout as L  # noqa: E402

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
SRC = os.path.join(ROOT, "src")
DATA = os.path.join(SRC, "ReplicatedStorage", "Cosmetics", "VoidWings", "VoidWingsData.luau")
OUT = os.path.join(ROOT, "install", "InstallVoidWings.lua")


def num(x):
    s = f"{x:.4f}".rstrip("0").rstrip(".")
    return s if s not in ("-0", "") else "0"


def vec(v):
    return "{ " + ", ".join(num(x) for x in v) + " }"


def data_source():
    feathers = []
    for fe in L.FEATHERS:
        feathers.append(
            f"\t\t{{ Base = {vec(fe['base'])}, Angle = {num(fe['angle'])}, Length = {num(fe['length'])}, "
            f"Depth = {num(fe['depth'])}, Frame = {fe['frame']}, Phase = {num(fe['phase'])}, Flutter = {num(fe['flutter'])} }},"
        )
    tip = L.CENTRELINE[3]
    # a point 72% along the centreline, for particle attachments (cell fractions, right wing)
    p = [(1 - 0.72) ** 3, 3 * (1 - 0.72) ** 2 * 0.72, 3 * (1 - 0.72) * 0.72 ** 2, 0.72 ** 3]
    mid = [sum(w * c[i] for w, c in zip(p, L.CENTRELINE)) for i in range(2)]

    def cell(pt):
        return ((pt[0] - L.FRAME_X[0]) / L.FRAME_W, (L.FRAME_Y[1] - pt[1]) / L.FRAME_H)

    return f"""--!strict
-- Void Wings geometry and motion. GENERATED by tools/voidwings/build.py from
-- tools/voidwings/layout.py (the same numbers drive the texture renderer and
-- the offline preview) - edit layout.py and rebuild, not this file.
--
-- Torso space: R6 Torso is 2x2x1, the back face is at z = +0.5 and the
-- character's right is +X. Numbers are for the right wing; the left wing is
-- its mirror image (x and every roll/sweep sign flipped, mirrored atlas).

return {{
	-- one sprite-sheet cell covers FrameW x FrameH feather lengths
	FrameW = {num(L.FRAME_W)},
	FrameH = {num(L.FRAME_H)},
	-- feather base / tip / particle point as fractions of the cell (u from the
	-- left, v from the top) in the right wing's image
	BaseU = {num(L.BASE_U)},
	BaseV = {num(L.BASE_V)},
	TipU = {num(cell(tip)[0])},
	TipV = {num(cell(tip)[1])},
	EmitU = {num(cell(mid)[0])},
	EmitV = {num(cell(mid)[1])},

	Grid = {L.GRID}, -- cells per atlas side
	Atlases = {L.ATLASES},
	Frames = {L.FRAMES},
	Fps = {L.FPS},

	WingRoot = {vec(L.WING_ROOT)},
	Sweep = {num(L.SWEEP_DEG)},
	Tilt = {num(L.TILT_DEG)},
	Scale = {num(L.SCALE)},

	BeatHz = {num(L.BEAT_HZ)},
	BeatDeg = {num(L.BEAT_DEG)},
	BeatLiftDeg = {num(L.BEAT_LIFT_DEG)},
	BreatheHz = {num(L.BREATHE_HZ)},
	BreatheStuds = {num(L.BREATHE_STUDS)},

	-- Base: wing-plane position from the wing root; Angle: degrees from
	-- straight up toward the outside; Frame: loop-frame offset; Phase/Flutter:
	-- per-feather flutter (radians / degrees), a ripple travelling outward
	Feathers = {{
{chr(10).join(feathers)}
	}},
}}
"""


# (name, class, home, parent or None, source path)
SCRIPTS = [
    ("Items", "ModuleScript", "cosmetics", None, "ReplicatedStorage/Cosmetics/Items.luau"),
    ("VoidWings", "ModuleScript", "cosmetics", None, "ReplicatedStorage/Cosmetics/VoidWings/init.luau"),
    ("VoidWingsData", "ModuleScript", "cosmetics", "VoidWings", "ReplicatedStorage/Cosmetics/VoidWings/VoidWingsData.luau"),
    ("VoidWingsAssets", "ModuleScript", "cosmetics", "VoidWings", "ReplicatedStorage/Cosmetics/VoidWings/VoidWingsAssets.luau"),
    ("Preview", "ModuleScript", "cosmetics", None, "ReplicatedStorage/Cosmetics/Preview.luau"),
    ("CosmeticsServer", "Script", "server", None, "ServerScriptService/CosmeticsServer.server.luau"),
    ("CosmeticsClient", "LocalScript", "client", None, "StarterPlayerScripts/CosmeticsClient.client.luau"),
]

HEADER = '''-- Void Wings installer (Mythic, exclusive: granted to merreystantach2).
-- Paste this whole file into Studio's command bar (View > Command Bar) and
-- press Enter. It creates/updates ReplicatedStorage.Cosmetics (catalog, wing
-- rig, viewport preview), ServerScriptService.CosmeticsServer and
-- StarterPlayerScripts.CosmeticsClient. One undo step (Ctrl+Z reverts it).
-- Texture ids already in your VoidWingsAssets are kept.
-- Generated by tools/voidwings/build.py from src/ - edit those, not this.

local ChangeHistoryService = game:GetService("ChangeHistoryService")
local ReplicatedStorage = game:GetService("ReplicatedStorage")
local ServerScriptService = game:GetService("ServerScriptService")
local StarterPlayer = game:GetService("StarterPlayer")

local SOURCES = {}
'''

BODY = '''
local SCRIPTS = {
%s
}

local recording
pcall(function()
	recording = ChangeHistoryService:TryBeginRecording("Install Void Wings")
end)

local log = {}

local function put(parent, className, name, source)
	local existing = parent:FindFirstChild(name)
	local fits = existing and (if className == "ModuleScript"
		then existing:IsA("ModuleScript")
		else existing:IsA("BaseScript"))
	if existing and not fits then
		existing.Name = name .. "_Old"
		table.insert(log, "renamed unexpected " .. existing.ClassName .. " to " .. existing:GetFullName())
		existing = nil
	end
	local script = existing or Instance.new(className)
	script.Name = name
	script.Source = source
	script.Parent = parent
	table.insert(log, (existing and "updated " or "created ") .. script:GetFullName())
	return script
end

local cosmetics = ReplicatedStorage:FindFirstChild("Cosmetics")
if cosmetics and not cosmetics:IsA("Folder") then
	cosmetics.Name = "Cosmetics_Old"
	cosmetics = nil
end
if not cosmetics then
	cosmetics = Instance.new("Folder")
	cosmetics.Name = "Cosmetics"
	cosmetics.Parent = ReplicatedStorage
	table.insert(log, "created " .. cosmetics:GetFullName())
end

if not ReplicatedStorage:FindFirstChild("CosmeticsRemote") then
	local remote = Instance.new("RemoteEvent")
	remote.Name = "CosmeticsRemote"
	remote.Parent = ReplicatedStorage
	table.insert(log, "created " .. remote:GetFullName())
end

local clientHome = StarterPlayer:FindFirstChildOfClass("StarterPlayerScripts")
	or StarterPlayer:WaitForChild("StarterPlayerScripts")
local HOMES = { cosmetics = cosmetics, server = ServerScriptService, client = clientHome }

-- keep texture ids already uploaded into this place
do
	local rig = cosmetics:FindFirstChild("VoidWings")
	local current = rig and rig:FindFirstChild("VoidWingsAssets")
	local old = current and current:IsA("ModuleScript") and current.Source or ""
	local kept = 0
	for key, id in old:gmatch('([%%w_]+)%%s*=%%s*"(rbxassetid://%%d+)"') do
		local before = SOURCES.VoidWingsAssets
		SOURCES.VoidWingsAssets = before:gsub('(%%f[%%w_]' .. key .. '%%s*=%%s*)"[^"]*"', '%%1"' .. id .. '"', 1)
		if SOURCES.VoidWingsAssets ~= before then
			kept += 1
		end
	end
	for key, flag in old:gmatch('(Frame[%%w_]+)%%s*=%%s*(%%a+)') do
		if flag == "true" then
			SOURCES.VoidWingsAssets = SOURCES.VoidWingsAssets:gsub('(%%f[%%w_]' .. key .. '%%s*=%%s*)false', '%%1true', 1)
		end
	end
	if kept > 0 then
		table.insert(log, "kept " .. kept .. " texture ids from your VoidWingsAssets")
	end
end

local made = {}
for _, entry in ipairs(SCRIPTS) do
	local parent = entry.parent and made[entry.parent] or HOMES[entry.home]
	made[entry.name] = put(parent, entry.class, entry.name, SOURCES[entry.name])
end

if recording then
	ChangeHistoryService:FinishRecording(recording, Enum.FinishRecordingOperation.Commit)
else
	pcall(function()
		ChangeHistoryService:SetWaypoint("Install Void Wings")
	end)
end

print("Void Wings installed:")
for _, line in ipairs(log) do
	print("  " .. line)
end
'''


def delimiter(sources):
    level = 3
    while any(("]" + "=" * level + "]") in s for s in sources):
        level += 1
    return "=" * level


def lua_str(s):
    return '"' + s + '"' if s is not None else "nil"


def main():
    os.makedirs(os.path.dirname(DATA), exist_ok=True)
    with open(DATA, "w") as f:
        f.write(data_source())
    print("wrote", os.path.relpath(DATA, ROOT))

    texts = []
    for name, cls, home, parent, path in SCRIPTS:
        with open(os.path.join(SRC, path)) as f:
            texts.append((name, cls, home, parent, f.read()))
    eq = delimiter([t[4] for t in texts])
    parts = [HEADER]
    for name, _, _, _, text in texts:
        # a long bracket drops a leading newline, so add one to keep line 1 intact
        parts.append(f"\nSOURCES.{name} = [{eq}[\n{text}]{eq}]\n")
    rows = ",\n".join(
        f'\t{{ name = "{n}", class = "{c}", home = "{h}", parent = {lua_str(p)} }}'
        for n, c, h, p, _ in texts
    )
    parts.append(BODY % rows)
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        f.write("".join(parts))
    print("wrote", os.path.relpath(OUT, ROOT))


if __name__ == "__main__":
    main()
